#pragma once

#include "parser.hpp"
#include "scope.hpp"
#include <ely/core/chunk.hpp>
#include <ely/core/opcode.hpp>
#include <ely/core/value.hpp>
#include <cstdint>
#include <optional>
#include <string_view>

namespace ely::compiler {

/**
 * Single-pass bytecode compiler translating Elysabettian source code
 * into an executable bytecode Chunk for the virtual machine.
 */
class Compiler {
public:
    /**
     * Constructs a new Compiler instance targeting the given source text and function kind.
     *
     * @param source Non-owning slice of the source code string.
     * @param type Kind of function or script being compiled.
     */
    explicit Compiler(std::string_view source, FunctionType type = FunctionType::Script);

    /**
     * Compiles the source stream and returns the generated bytecode chunk.
     *
     * @return The populated Chunk, or std::nullopt if any syntax or semantic error occurred.
     */
    [[nodiscard]] std::optional<core::Chunk> compile();

private:
    /**
     * Returns the 1-based source line number of the most recently consumed token.
     */
    [[nodiscard]] uint32_t current_line() const noexcept {
        return m_parser.previous().line;
    }

    /**
     * Appends a raw byte to the bytecode stream at the current source line.
     */
    void emit_byte(uint8_t byte) noexcept;

    /**
     * Appends an opcode instruction to the bytecode stream at the current source line.
     */
    void emit_opcode(core::Opcode op) noexcept;

    /**
     * Appends two consecutive bytes to the bytecode stream.
     */
    void emit_bytes(uint8_t byte1, uint8_t byte2) noexcept;

    /**
     * Emits a function return sequence (handling constructor returns for initializers).
     */
    void emit_return() noexcept;

    /**
     * Adds a value to the constant pool and emits a Constant opcode instruction.
     */
    void emit_constant(core::Value value) noexcept;

    /**
     * Emits a forward jump instruction with placeholder 16-bit offset operands.
     *
     * @param jump_op Jump opcode to emit (e.g., Opcode::Jump or Opcode::JumpZero).
     * @return Bytecode offset of the placeholder operands to be patched later.
     */
    [[nodiscard]] size_t emit_jump(core::Opcode jump_op) noexcept;

    /**
     * Patches a previously emitted forward jump with the calculated relative jump offset.
     *
     * @param offset Bytecode offset returned by emit_jump.
     */
    void patch_jump(size_t offset) noexcept;

    /**
     * Emits an unconditional backward loop jump instruction to the given target offset.
     *
     * @param loop_start Bytecode offset where the loop began.
     */
    void emit_loop(size_t loop_start) noexcept;

    /// Parser that extracts and tracks the token stream.
    Parser m_parser;
    /// Bytecode chunk currently being constructed.
    core::Chunk m_chunk;
    /// Lexical scoping and local variable context.
    CompilerContext m_context;
};

} // namespace ely::compiler
