#pragma once

#include "parser.hpp"
#include "scope.hpp"
#include <ely/core/chunk.hpp>
#include <ely/core/opcode.hpp>
#include <ely/core/value.hpp>
#include <cstdint>
#include <optional>
#include <string_view>

namespace ely::compiler {

/**
 * Single-pass bytecode compiler translating Elysabettian source code
 * into an executable bytecode Chunk for the virtual machine.
 */
class Compiler {
public:
    /**
     * Constructs a new Compiler instance targeting the given source text and function kind.
     *
     * @param source Non-owning slice of the source code string.
     * @param type Kind of function or script being compiled.
     */
    explicit Compiler(std::string_view source, FunctionType type = FunctionType::Script);

    /**
     * Compiles the source stream and returns the generated bytecode chunk.
     *
     * @return The populated Chunk, or std::nullopt if any syntax or semantic error occurred.
     */
    [[nodiscard]] std::optional<core::Chunk> compile();

private:
    /**
     * Returns the 1-based source line number of the most recently consumed token.
     */
    [[nodiscard]] uint32_t current_line() const noexcept {
        return m_parser.previous().line;
    }

    /**
     * Appends a raw byte to the bytecode stream at the current source line.
     *
     * @param byte 8-bit value to write.
     */
    void emit_byte(uint8_t byte) noexcept;

    /**
     * Appends an opcode instruction to the bytecode stream at the current source line.
     *
     * @param op Opcode to emit.
     */
    void emit_opcode(core::Opcode op) noexcept;

    /**
     * Appends two consecutive bytes to the bytecode stream.
     *
     * @param byte1 First byte to emit.
     * @param byte2 Second byte to emit.
     */
    void emit_bytes(uint8_t byte1, uint8_t byte2) noexcept;

    /**
     * Emits a function return sequence (handling constructor returns for initializers).
     */
    void emit_return() noexcept;

    /**
     * Adds a value to the constant pool and emits a Constant opcode instruction.
     *
     * @param value Value literal to store and load.
     */
    void emit_constant(core::Value value) noexcept;

    /**
     * Emits a forward jump instruction with placeholder 16-bit offset operands.
     *
     * @param jump_op Jump opcode to emit (e.g., Opcode::Jump or Opcode::JumpZero).
     * @return Bytecode offset of the placeholder operands to be patched later.
     */
    [[nodiscard]] size_t emit_jump(core::Opcode jump_op) noexcept;

    /**
     * Patches a previously emitted forward jump with the calculated relative jump offset.
     *
     * @param offset Bytecode offset returned by emit_jump.
     */
    void patch_jump(size_t offset) noexcept;

    /**
     * Emits an unconditional backward loop jump instruction to the given target offset.
     *
     * @param loop_start Bytecode offset where the loop began.
     */
    void emit_loop(size_t loop_start) noexcept;

    /**
     * Enters a new nested lexical scope block.
     */
    void begin_scope() noexcept;

    /**
     * Exits the current lexical scope block and emits Opcode::Pop for all discarded locals.
     */
    void end_scope() noexcept;

    /**
     * Registers a new local variable on the current call frame stack.
     *
     * @param name Identifier token of the local variable.
     */
    void add_local(Token name);

    /**
     * Declares a variable in the current scope, checking for duplicate definitions at the same depth.
     */
    void declare_variable();

    /**
     * Marks the most recently declared local variable as initialized and usable.
     */
    void mark_initialized() noexcept;

    /**
     * Resolves an identifier token to its stack slot index in the current frame.
     *
     * @param name Identifier token to look up.
     * @return 0-based stack slot index, or std::nullopt if the variable is not in local scope.
     */
    [[nodiscard]] std::optional<uint8_t> resolve_local(Token name);

    /**
     * Compiles an expression at the assignment precedence level.
     */
    void expression();

    /**
     * Parses an expression with precedence equal to or greater than the specified level.
     *
     * @param precedence Minimum precedence boundary to parse.
     */
    void parse_precedence(Precedence precedence);

    /**
     * Resolves the infix precedence level associated with a token type.
     *
     * @param token_type Token type to inspect.
     * @return Corresponding Precedence level.
     */
    [[nodiscard]] static constexpr Precedence get_precedence(TokenType token_type) noexcept;

    /**
     * Compiles a numeric constant literal.
     */
    void number();

    /**
     * Parses an expression wrapped in grouping parentheses.
     */
    void grouping();

    /**
     * Parses an expression starting with a unary prefix operator.
     */
    void unary();

    /**
     * Parses an infix binary operator expression and emits the corresponding opcode.
     */
    void binary();

    /**
     * Parses a literal keyword expression (true, false, null).
     */
    void literal();

    /**
     * Parses a string literal and loads it into the string constant pool.
     */
    void string();

    /**
     * Compiles a short-circuiting logical AND expression.
     */
    void and_op();

    /**
     * Compiles a short-circuiting logical OR expression.
     */
    void or_op();

    /**
     * Parses a function invocation argument list and call instruction.
     */
    void call();

    /**
     * Parses comma-separated arguments enclosed in parentheses.
     *
     * @return Total count of arguments parsed.
     */
    [[nodiscard]] uint8_t argument_list();

    /**
     * Compiles a variable identifier expression (read or assignment).
     *
     * @param can_assign True if the variable is in an assignable context.
     */
    void variable(bool can_assign);

    /**
     * Emits bytecode to resolve or assign a named identifier.
     *
     * @param name Identifier token.
     * @param can_assign True if assignment is permitted.
     */
    void named_variable(Token name, bool can_assign);

    /**
     * Parses a prefix increment or decrement expression (++x or --x).
     */
    void prefix_inc_dec();

    /**
     * Parses a postfix increment or decrement expression (x++ or x--).
     *
     * @param get_op Opcode used to read variable (GetLocal or GetGlobal).
     * @param set_op Opcode used to write variable (SetLocal or SetGlobal).
     * @param arg Stack slot index or constant pool name index.
     */
    void postfix_inc_dec(core::Opcode get_op, core::Opcode set_op, uint8_t arg);

    /**
     * Stores an identifier string in the constant pool and returns its index.
     *
     * @param name Token containing the identifier string.
     * @return 8-bit index in the constant pool.
     */
    [[nodiscard]] uint8_t identifier_constant(Token name);

    /**
     * Dispatches and compiles a single statement.
     */
    void statement();

    /**
     * Dispatches top-level declarations (variable bindings, functions, or fallthrough statements).
     */
    void declaration();

    /**
     * Compiles a print statement (`print <expr>;`).
     */
    void print_statement();

    /**
     * Compiles an expression evaluated for side effects, discarding its value from the stack.
     */
    void expression_statement();

    /**
     * Parses a variable declaration statement (`var <name> [= <expr>];`).
     */
    void var_declaration();

    /**
     * Compiles a conditional branching statement (`if (<cond>) <then> [else <else>]`).
     */
    void if_statement();

    /**
     * Compiles a while loop statement (`while (<cond>) <body>`).
     */
    void while_statement();

    /**
     * Compiles a C-style for loop (`for (<init>; <cond>; <inc>) <body>`).
     */
    void for_statement();

    /**
     * Compiles a function return statement (`return [<expr>];`).
     */
    void return_statement();

    /**
     * Compiles an import statement loading dynamic or standard modules.
     */
    void import_statement();

    /**
     * Compiles a function definition declaration (`func <name>(...) { ... }`).
     */
    void function_declaration();

    /**
     * Compiles a function body, parameter list, and creates a nested compiled chunk.
     *
     * @return Number of compiled parameters (arity).
     */
    size_t function();

    /**
     * Parses a sequence of declarations enclosed in a block (`{ ... }`).
     */
    void block();

    /**
     * Recovers parser state to the next statement boundary after a syntax error.
     */
    void synchronize();

    /**
     * Consumes an identifier token and returns its constant pool index for globals, or 0 for locals.
     *
     * @param error_message Error message to emit if an identifier is missing.
     * @return Constant pool index if a global variable, or 0 if local.
     */
    [[nodiscard]] uint8_t parse_variable(std::string_view error_message);

    /**
     * Emits instructions to bind a variable in global or local scope.
     *
     * @param global Constant pool index for global variables.
     */
    void define_variable(uint8_t global);

    /// Parser that extracts and tracks the token stream.
    Parser m_parser;
    /// Bytecode chunk currently being constructed.
    core::Chunk m_chunk;
    /// Lexical scoping and local variable context.
    CompilerContext m_context;

    /// Max number of local variables in a function or scope.
    static constexpr size_t kMaxLocals = 256;

    /// Max number of function arguments / parameters.
    static constexpr uint8_t kMaxArgs = 255;
};

} // namespace ely::compiler
